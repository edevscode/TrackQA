import { lstat, mkdir, open, realpath, rmdir, unlink } from 'node:fs/promises'
import path from 'node:path'
import { ConnectorError, requireValue, setupFor, UUID } from '../core.ts'
import type { Setup } from '../core.ts'
import { fingerprint } from './codex.ts'
import { commitWindowsSettings } from './gemini-windows.ts'

// Reuse the existing private Windows file writer, not Gemini's settings editor.
// These files live only in the connector recovery directory, never Claude's home.
export const claudeEntry = (setup: Setup) => ({ type: 'http', url: setup.endpoint, headers: { Authorization: `Bearer \${${setup.envVar}}` } })
export function claudeSessionPath(home: string, setup: Setup) {
  requireValue(path.isAbsolute(home) && UUID.test(setup.projectId)
    && fingerprint(setup) === fingerprint(setupFor(setup.projectId, 'claude')), 'configuration_location_untrusted')
  return path.join(home, setup.projectId, 'settings.json')
}
const payload = (setup: Setup) => Buffer.from(JSON.stringify({ mcpServers: { [setup.serverName]: claudeEntry(setup) } }, null, 2) + '\n')
export const matchesClaudeEntry = (value: unknown, setup: Setup) => !!value && fingerprint(value) === fingerprint(claudeEntry(setup))

async function directory(home: string, setup: Setup, create = false) {
  const file = claudeSessionPath(home, setup)
  for (const dir of [home, path.dirname(file)]) {
    if (create) await mkdir(dir, { recursive: true, mode: 0o700 })
    try {
      const info = await lstat(dir)
      requireValue(info.isDirectory() && !info.isSymbolicLink()
        && (await realpath(dir)).toLowerCase() === path.resolve(dir).toLowerCase(), 'configuration_location_untrusted')
    } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error }
  }
  return file
}
export async function readClaudeSession(home: string, setup: Setup) {
  const file = await directory(home, setup)
  try {
    const info = await lstat(file)
    requireValue(info.isFile() && !info.isSymbolicLink() && info.nlink === 1 && info.size <= 4096, 'configuration_changed')
    const handle = await open(file, 'r')
    try {
      const actual = await handle.stat()
      requireValue(actual.ino === info.ino && actual.dev === info.dev && actual.size === info.size, 'configuration_changed')
      const bytes = await handle.readFile()
      // Exact connector-generated bytes only: no additional servers, JSONC,
      // duplicate keys, credentials or externally changed entries are accepted.
      requireValue(bytes.equals(payload(setup)), 'configuration_changed')
      return claudeEntry(setup)
    } finally { await handle.close() }
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null
    if (error instanceof ConnectorError) throw error
    throw new ConnectorError('configuration_unreadable')
  }
}
export async function installClaudeSession(home: string, setup: Setup, commit = commitWindowsSettings) {
  requireValue(await readClaudeSession(home, setup) === null, 'configuration_conflict')
  const file = await directory(home, setup, true)
  await commit(file, { exists: false, hash: null }, payload(setup))
  requireValue(await readClaudeSession(home, setup) !== null, 'installation_unconfirmed')
  return fingerprint(claudeEntry(setup))
}
export async function removeClaudeSession(home: string, setup: Setup, hash: string | null) {
  const entry = await readClaudeSession(home, setup)
  if (entry === null) return
  // A crash after file creation but before journal acknowledgement is recoverable
  // from the exact token-free payload in this owned, project-specific location.
  requireValue(hash === null || fingerprint(entry) === hash, 'configuration_changed')
  const file = claudeSessionPath(home, setup)
  await unlink(file)
  await rmdir(path.dirname(file)) // Never recursively delete an unexpected file.
  requireValue(await readClaudeSession(home, setup) === null, 'removal_unconfirmed')
}
